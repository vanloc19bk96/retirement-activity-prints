/**
 * The hidden pictures, drawn square by square for this game.
 *
 * Every picture is retirement's good life in a few dozen squares: a cup of
 * tea, a sailboat, a golf flag, a camper van, a typewriter to say goodbye
 * to. Each was drawn for its grid, not scaled down from something larger,
 * so the picture a reader uncovers is crisp at the size they solve it —
 * and every one is proven (tests and at print time) to solve line by line
 * with no guessing, in both the way it is drawn and its mirror image.
 *
 * `#` is a shaded square, `.` a blank one. Rows are top to bottom.
 */

export type PlTheme = 'home' | 'travel' | 'garden' | 'hobbies'

export interface PlPicture {
  id: string
  /** What the reader writes on the "Mystery picture" line, and the answer page prints. */
  name: string
  theme: PlTheme
  /** False for a picture that only reads one way round. */
  mirror: boolean
  art: readonly string[]
}

