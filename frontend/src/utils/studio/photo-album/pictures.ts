/**
 * The snapshots, drawn square by square for this game.
 *
 * Every picture is a moment from a retiree's album: fruit from the
 * farmers' market, a rain boot by the back door, a teddy bear for the
 * grandchildren, reading glasses on a paperback, a log cabin, a steam
 * train, the Eiffel Tower at last. Each was drawn for its grid, square by
 * square, not scaled down from something larger, so the snapshot a reader
 * develops is crisp at the size they solve it. Every one is proven (tests
 * and at print time) to build grids its level's own steps finish, both the
 * way it is drawn and, where it reads either way, its mirror image.
 *
 * `#` is a shaded square, `.` a blank one. Rows are top to bottom, and every
 * picture fills its level's square grid.
 */

export interface PaPicture {
  id: string
  /** What the reader writes on the snapshot's caption line, and the answer page prints. */
  name: string
  /** False for a picture that reads the same, or only one way, mirrored. */
  mirror: boolean
  art: readonly string[]
}

