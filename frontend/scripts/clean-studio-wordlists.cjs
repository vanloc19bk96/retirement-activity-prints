function normalize(list) {
  const seen = new Set()
  const out = []
  for (const raw of list) {
    const w = String(raw)
      .toUpperCase()
      .replace(/[^A-Z]/g, '')
    if (w.length < 3 || w.length > 12) continue
    if (GLOBAL_REJECT.has(w)) continue
    if (seen.has(w)) continue
    seen.add(w)
    out.push(w)
  }
  return out.sort((a, b) => a.localeCompare(b))
}

function cutBefore(list, marker) {
  const i = list.indexOf(marker)
  if (i < 0) return list
  return list.slice(0, i)
}

const counts = {}

for (const file of fs.readdirSync(dir).filter((f) => f.endsWith('-en.json'))) {
  if (file === 'animals-en.json') {
    counts.animals = JSON.parse(fs.readFileSync(path.join(dir, file), 'utf8')).length
    continue
  }

  let list = JSON.parse(fs.readFileSync(path.join(dir, file), 'utf8'))

  if (file === 'school-en.json') {
    const early = list.slice(0, 220)
    const fromKeep = list.filter((w) => SCHOOL_KEEP.has(String(w).toUpperCase()))
    list = [...early, ...fromKeep]
  } else if (CUT_BEFORE[file]) {
    list = cutBefore(list, CUT_BEFORE[file])
  }

  const extra = EXTRA_REJECT[file]
  if (extra) list = list.filter((w) => !extra.has(String(w).toUpperCase()))

  list = normalize(list)
  fs.writeFileSync(path.join(dir, file), JSON.stringify(list, null, 2) + '\n')
  const theme = file.replace('-en.json', '')
  counts[theme] = list.length
  console.log(file, list.length, 'sample:', list.slice(0, 5).join(','), '...', list.slice(-5).join(','))
}

const indexPath = path.join(dir, 'index.json')
const index = JSON.parse(fs.readFileSync(indexPath, 'utf8'))
for (const entry of index) {
  if (counts[entry.key] != null) entry.count = counts[entry.key]
}
fs.writeFileSync(indexPath, JSON.stringify(index, null, 2) + '\n')
console.log(
  '\nindex:',
  index.map((e) => `${e.key}:${e.count}`).join(' '),
)
